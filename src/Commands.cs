// Coder CLI (.NET 11 port) — /init command: generate an AGENTS.md for the project.
// Ported from src/commands/init.ts.

using System.Text;
using System.Text.Json;
using Coder.Types;

namespace Coder.Commands;

public static class InitCommand
{
    /// <summary>Scan the project and write AGENTS.md. Returns the target path.</summary>
    public static async Task<string> GenerateAgentsAsync(CoderConfig cfg, Action<string>? info = null)
    {
        var cwd = cfg.Cwd;
        info?.Invoke($"Scanning {cwd}…");

        var pkg = ReadPackageJson(cwd);
        var files = ListTopLevel(cwd);
        var existing = files.FirstOrDefault(f => string.Equals(f, "AGENTS.md", StringComparison.OrdinalIgnoreCase));
        if (existing != null) info?.Invoke($"Existing {existing} found — overwriting.");

        var s = new List<string>
        {
            "# AGENTS.md — Coder CLI project context\n",
            $"> Generated by `/init` at {DateTime.UtcNow:yyyy-MM-dd}.\n",
        };

        if (pkg.HasValue)
        {
            var p = pkg.Value;
            s.Add("## Project");
            s.Add($"- **Name:** {GetStr(p, "name") ?? "_(unnamed)_"}");
            s.Add($"- **Version:** {GetStr(p, "version") ?? "_(none)_"}");
            s.Add($"- **Description:** {GetStr(p, "description") ?? "_(none)_"}");
            AppendMap(s, p, "scripts", "\n## Scripts", (k, v) => $"- `{k}`: `{v}`");
            AppendMap(s, p, "dependencies", "\n## Runtime dependencies", (k, v) => $"- {k}@{v}");
            AppendMap(s, p, "devDependencies", "\n## Dev dependencies", (k, v) => $"- {k}@{v}");
        }
        else
        {
            s.Add("## Project");
            s.Add("_(no package.json found at project root)_");
        }

        s.Add("\n## Repository layout");
        s.Add("```");
        s.AddRange(files.Take(40));
        if (files.Count > 40) s.Add($"…({files.Count - 40} more)");
        s.Add("```");

        s.Add("\n## Conventions");
        s.Add("- Code style: _(fill in — e.g. formatter, linter, naming)_");
        s.Add("- Testing: _(how to run, what to verify)_");
        s.Add("- Build: _(commands + artifacts)_");
        s.Add("- Deploy: _(if applicable)_");

        s.Add("\n## Working agreement with Coder CLI");
        s.Add("- Coder CLI should ask before destructive operations unless `/permission-mode acceptEdits`.");
        s.Add("- Coder CLI should prefer targeted edits (file_edit) over full rewrites (file_write).");
        s.Add("- Coder CLI should run tests after non-trivial changes and report results.");
        s.Add("- For multi-step work, Coder CLI should use todo_write and update progress visibly.");
        s.Add("- Coder CLI should commit only when explicitly asked, with a clear message.");

        var target = Path.Combine(cwd, "AGENTS.md");
        await File.WriteAllTextAsync(target, string.Join("\n", s) + "\n");
        return target;
    }

    private static void AppendMap(List<string> sink, JsonElement root, string key, string heading,
        Func<string, string, string> fmt)
    {
        if (!root.TryGetProperty(key, out var el) || el.ValueKind != JsonValueKind.Object) return;
        sink.Add(heading);
        foreach (var prop in el.EnumerateObject())
            sink.Add(fmt(prop.Name, prop.Value.ValueKind == JsonValueKind.String ? prop.Value.GetString() ?? "" : prop.Value.ToString()));
    }

    private static string? GetStr(JsonElement root, string key)
        => root.TryGetProperty(key, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString() : null;

    private static JsonElement? ReadPackageJson(string cwd)
    {
        try
        {
            var file = Path.Combine(cwd, "package.json");
            if (!File.Exists(file)) return null;
            using var doc = JsonDocument.Parse(File.ReadAllText(file));
            return doc.RootElement.Clone();
        }
        catch { return null; }
    }

    private static List<string> ListTopLevel(string cwd)
    {
        try
        {
            var outList = new List<string>();
            foreach (var d in Directory.EnumerateDirectories(cwd))
            {
                var name = Path.GetFileName(d);
                if (name.StartsWith('.')) continue;
                outList.Add(name + "/");
            }
            foreach (var f in Directory.EnumerateFiles(cwd))
            {
                var name = Path.GetFileName(f);
                if (name.StartsWith('.') && name != ".gitignore") continue;
                outList.Add(name);
            }
            outList.Sort(StringComparer.Ordinal);
            return outList;
        }
        catch { return new List<string>(); }
    }
}
